const form = document.querySelector('#form');
const result = document.querySelector('#result');
const language = new URLSearchParams(location.search).get('lang');
const locale = language === 'en' || language === 'ja' ? language : 'zh-TW';
const copy = messages[locale];
const numberFormat = new Intl.NumberFormat(locale);
const money = n => numberFormat.format(n);
const listingInput = document.querySelector('#url');

document.documentElement.lang = locale;
for (const element of document.querySelectorAll('[data-copy]')) {
  element.textContent = copy[element.dataset.copy];
}
listingInput.setAttribute('aria-label', copy.linkLabel);

const lookupErrors = ['invalid', 'unavailable', 'removed', 'unconfirmed', 'lookupFailed'];
function errorMessage(error) {
  if (locale === 'zh-TW' && error?.error) return error.error;
  const key = lookupErrors.find(key => messages['zh-TW'][key] === error?.error);
  return copy[key] || copy.unknown;
}
const escapeHtml = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

function quoteCard(x) {
  const image = x.image ? `<img src="${escapeHtml(x.image)}" alt="${copy.image}">` : '<div></div>';
  return `
    <article class="card">
      ${image}
      <div>
        <div class="ok">● ${copy.available}</div>
        <h2>${escapeHtml(x.title || x.itemId)}</h2>
        <div class="row"><span>${copy.price}</span><b>¥${money(x.yen)}</b></div>
        <div class="row"><span>${copy.converted} (× ${x.rate})</span><b>NT$${money(x.itemTwd)}</b></div>
        <div class="row"><span>${copy.fee}</span><b>NT$${money(x.fee)}</b></div>
        <div class="row total"><span>${copy.total}</span><span>NT$${money(x.total)}</span></div>
        <p class="hint">${copy.shipping}</p>
        <button id="confirm-purchase" class="confirm-btn">${copy.confirm}</button>
        <p class="purchase-note">${copy.confirmNote}</p>
      </div>
    </article>
  `;
}

function purchaseReady(x) {
  return `
    <div class="purchase-ready">
      <div class="ok">✓ ${copy.created}</div>
      <h3>${escapeHtml(x.title)}</h3>
      <div class="row total"><span>${copy.purchasePrice}</span><span>NT$${money(x.total)}</span></div>
      <div class="purchase-actions">
        <a class="secondary-action" target="_top" href="${escapeHtml(x.cartUrl)}">${copy.cart}</a>
        <a class="primary-action" target="_top" href="${escapeHtml(x.checkoutUrl)}">${copy.checkout}</a>
      </div>
      <a class="product-link" target="_top" href="${escapeHtml(x.productUrl)}">${copy.product} →</a>
    </div>
  `;
}

const btn = form.querySelector('button');
let quoteRevision = 0;

listingInput.addEventListener('input', () => {
  quoteRevision++;
  result.innerHTML = '';
});

form.addEventListener('submit', async e => {
  e.preventDefault();
  if (btn.disabled) return;
  const url = listingInput.value.trim();
  const revision = ++quoteRevision;
  const isCurrentQuote = () => revision === quoteRevision && listingInput.value.trim() === url;
  btn.disabled = true;
  btn.textContent = copy.loading;
  result.innerHTML = '';

  try {
    const r = await fetch('/api/quote', {
      method: 'POST',
      headers: {'content-type':'application/json'},
      body: JSON.stringify({url})
    });
    const x = await r.json();
    if (!isCurrentQuote()) return;
    if (!r.ok) throw x;
    result.innerHTML = quoteCard(x);

    const purchaseBtn = document.querySelector('#confirm-purchase');
    purchaseBtn.addEventListener('click', async () => {
      if (!isCurrentQuote() || purchaseBtn.disabled || btn.disabled) return;
      btn.disabled = true;
      listingInput.readOnly = true;
      purchaseBtn.disabled = true;
      purchaseBtn.textContent = copy.creating;

      try {
        const pr = await fetch('/api/purchase', {
          method: 'POST',
          headers: {'content-type':'application/json'},
          body: JSON.stringify({url: x.url})
        });
        const p = await pr.json();
        if (!isCurrentQuote()) return;
        if (!pr.ok) throw p;
        result.insertAdjacentHTML('beforeend', purchaseReady(p));
        purchaseBtn.textContent = copy.done;
      } catch (p) {
        if (!isCurrentQuote()) return;
        purchaseBtn.disabled = false;
        purchaseBtn.textContent = copy.confirm;
        const extra = p.setupRequired ? `<br><small>${copy.setup}</small>` : '';
        result.insertAdjacentHTML('beforeend', `<div class="error"><b>${copy.purchaseFailed}</b><br>${escapeHtml(errorMessage(p))}${extra}</div>`);
      } finally {
        listingInput.readOnly = false;
        btn.disabled = false;
      }
    });
  } catch (x) {
    if (!isCurrentQuote()) return;
    result.innerHTML = `<div class="error"><b>${copy.quoteFailed}</b><br>${escapeHtml(errorMessage(x))}${x.itemId ? `<br><small>${copy.itemId}: ${escapeHtml(x.itemId)}</small>` : ''}</div>`;
  } finally {
    btn.disabled = false;
    btn.textContent = copy.submit;
  }
});
